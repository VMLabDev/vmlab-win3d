static inline const uint8_t *font_glyph(char c)
{
    static const uint8_t blank[7] = {0};
    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');
    for (unsigned i = 0; i < sizeof font_table / sizeof font_table[0]; i++)
        if (font_table[i].c == c)
            return font_table[i].rows;
    return blank;
}

